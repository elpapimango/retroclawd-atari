#!/usr/bin/env python3
"""Writes p18_io_access_cost.s: what a bus access to each I/O register costs the CPU.

A counted loop `addq.l #1,d5 ; <one access> ; bra.s` runs for 4 frames per variant; the VBL handler stores the count of
every frame and moves the interrupted program to the next variant. An access that makes the CPU wait shows as fewer
iterations in a frame.

Result at $C000: header 'P18', then per variant 3 longs (frames 2 to 4 of its run; the first frame after a switch is
not stored)."""
import os

VARIANTS = [
    ("nop", "nop"),
    ("fdc_read", "move.w  $ff8604,d0"),
    ("fdc_write", "move.w  d4,$ff8604"),
    ("dma_mode_write", "move.w  d3,$ff8606"),
    ("dma_status_read", "move.w  $ff8606,d0"),
    ("dma_addr_read", "move.b  $ff8609,d0"),
    ("dma_addr_write", "move.b  d4,$ff860d"),
    ("mfp_read", "move.b  $fffa01,d0"),
    ("psg_read", "move.b  $ff8800,d0"),
    ("acia_read", "move.b  $fffc00,d0"),
    ("shifter_read", "move.w  $ff8240,d0"),
    ("rom_read", "move.w  $fc0000,d0"),
    ("acia_read_nop1", "nop\n    move.b  $fffc00,d0"),
    ("acia_read_nop2", "nop\n    nop\n    move.b  $fffc00,d0"),
    ("acia_read_nop3", "nop\n    nop\n    nop\n    move.b  $fffc00,d0"),
    ("acia_read_nop5", "nop\n    nop\n    nop\n    nop\n    nop\n    move.b  $fffc00,d0"),
]
FRAMES_PER = 4


def source():
    n = len(VARIANTS)
    blocks = "\n".join(
        f"v{i}:                            ; {name}\n    addq.l  #1,d5\n    {insn}\n    bra.s   v{i}" for i, (name, insn) in enumerate(VARIANTS)
    )
    table = "\n".join(f"    dc.l    v{i}" for i in range(n))
    return f'''; p18_io_access_cost.s: what a bus access to each I/O register costs the CPU.
; Generated by gen_p18.py: do not edit. See that file for what the probe records.
    .org $90000
    move.w  #$2700,sr
    clr.b   $fffa07             ; IERA, IERB, IMRA, IMRB: no MFP interrupt reaches the CPU
    clr.b   $fffa09
    clr.b   $fffa13
    clr.b   $fffa15
    lea     vbl(pc),a0
    move.l  a0,$70
    lea     $c000,a2
    move.l  #$50313800,(a2)+
    move.w  #$086,$ff8606       ; the FDC data register: accesses to it are harmless
    moveq   #$7f,d3
    add.w   #$7,d3              ; $86
    moveq   #0,d4
    moveq   #0,d5
    moveq   #-1,d6              ; frame counter (the first VBL makes it 0)
    lea     table(pc),a3
    move.w  #$2300,sr
idle:
    bra.s   idle

vbl:
    addq.w  #1,d6
    move.w  d6,d0
    ext.l   d0
    divu    #{FRAMES_PER},d0     ; d0 low = variant, high = frame within it
    move.l  d0,d1
    swap    d1                  ; the frame within the variant
    cmp.w   #0,d1
    beq.s   switch
    move.l  d5,(a2)+
    bra.s   next
switch:
    cmp.w   #{n},d0
    bge.s   finish
    lsl.w   #2,d0
    move.l  (a3,d0.w),2(sp)     ; resume in the variant's loop
next:
    moveq   #0,d5
    rte
finish:
    ori.w   #$0700,(sp)
    bra.s   next

table:
{table}
{blocks}
'''


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p18_io_access_cost.s"), "w", newline="\n") as f:
        f.write(source())
