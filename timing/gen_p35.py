#!/usr/bin/env python3
"""gen_p35.py: writes p35_midline_resolution.s and p45_midline_segments.s (the resolution register written part way along a line).

Both probes fill the screen with 80 distinct pseudo-random words on every line (so any reading of the words in low or medium
resolution can be told apart), set a 16-colour palette of distinct colours and use the HBL handler to write the resolution
register. Nothing is measured in memory; compare the screenshots.

P35 (two sweeps of one write):
  lines 100 to 171 (E2, k = 0 to 71): medium at the handler's start, low again after k NOPs: the segment ends 4 clocks later on
                                      each line;
  lines 172 to 243 (E1, k = 0 to 71): low at the handler's start, medium after k NOPs and left on until the next handler's
                                      first write: the segment starts 4 clocks later on each line.
  Every other line's handler leaves the register low.

P45 (a medium segment of two writes):
  lines 100 to 163 (k = 0 to 63): medium starts after k NOPs of the prefix slide and lasts a fixed time (16 NOPs and the
                                  handler's own instructions): the start moves 4 clocks a line;
  lines 164 to 227 (k = 0 to 63): medium starts after a fixed prefix (24 NOPs) and lasts k NOPs more."""
import os

here = os.path.dirname(os.path.abspath(__file__))

PALETTE = [0x000, 0x700, 0x070, 0x007, 0x770, 0x707, 0x077, 0x777, 0x444, 0x520, 0x052, 0x205, 0x631, 0x136, 0x363, 0x555]


def word(i: int) -> int:
    return ((i * 40503 + 12345) ^ (i * i * 77 + 0x5A5A)) & 0xFFFF


def nops(a, rows: int) -> None:
    for _ in range(rows):
        a("    dc.w    " + ",".join(["$4E71"] * 16))


def program(title: str, name: str, handler) -> str:
    lines: list[str] = []
    a = lines.append
    a("; %s (generated by gen_p35.py: do not edit)" % name)
    a("; %s" % title)
    a("    .org $90000")
    a("    move.w  #$2700,sr")
    for reg in ("07", "09", "13", "15"):
        a("    clr.b   $fffa%s" % reg)
    a("    moveq   #0,d0")
    a("    move.b  $ff8201,d0")
    a("    lsl.l   #8,d0")
    a("    move.b  $ff8203,d0")
    a("    lsl.l   #8,d0")
    a("    movea.l d0,a0")
    a("    move.w  #199,d1")
    a("fill_line:")
    a("    lea     words(pc),a1")
    a("    moveq   #79,d2")
    a("fill_word:")
    a("    move.w  (a1)+,(a0)+")
    a("    dbf     d2,fill_word")
    a("    dbf     d1,fill_line")
    a("    lea     palette(pc),a1")
    a("    lea     $ff8240,a2")
    a("    moveq   #15,d2")
    a("set_pal:")
    a("    move.w  (a1)+,(a2)+")
    a("    dbf     d2,set_pal")
    a("    lea     hbl(pc),a0")
    a("    move.l  a0,$68")
    a("    lea     vbl(pc),a0")
    a("    move.l  a0,$70")
    a("    moveq   #0,d6")
    a("    moveq   #0,d7")
    a("    move.w  #$2100,sr")
    a("idle:")
    a("    stop    #$2100")
    a("    bra.s   idle")
    a("")
    a("vbl:")
    a("    move.w  #$2100,(sp)")
    a("    addq.w  #1,d6")
    a("    moveq   #0,d7")
    a("    rte")
    a("")
    handler(a)
    a("palette:")
    a("    dc.w    " + ",".join("$%03x" % c for c in PALETTE))
    a("words:")
    for r in range(10):
        a("    dc.w    " + ",".join("$%04x" % word(r * 8 + c) for c in range(8)))
    return "\n".join(lines) + "\n"


E2_FIRST, E1_FIRST, COUNT = 100, 172, 72


def sweeps(a) -> None:
    a("hbl:")
    a("    addq.w  #1,d7")
    a("    move.w  d7,d0")
    a("    sub.w   #%d,d0" % E2_FIRST)
    a("    cmp.w   #%d,d0" % COUNT)
    a("    bcs.w   e2")
    a("    sub.w   #%d,d0" % (E1_FIRST - E2_FIRST))
    a("    cmp.w   #%d,d0" % COUNT)
    a("    bcs.w   e1")
    a("out:")
    a("    clr.b   $ff8260             ; low")
    a("    rte")
    a("")
    a("e2:                             ; medium at the start, low after d0 NOPs")
    a("    move.b  #1,$ff8260")
    a("    add.w   d0,d0")
    a("    lea     e2_end(pc),a1")
    a("    suba.w  d0,a1")
    a("    jmp     (a1)")
    nops(a, COUNT // 16 + 1)
    a("e2_end:")
    a("    clr.b   $ff8260")
    a("    rte")
    a("")
    a("e1:                             ; low at the start, medium after d0 NOPs")
    a("    clr.b   $ff8260")
    a("    add.w   d0,d0")
    a("    lea     e1_end(pc),a1")
    a("    suba.w  d0,a1")
    a("    jmp     (a1)")
    nops(a, COUNT // 16 + 1)
    a("e1_end:")
    a("    move.b  #1,$ff8260")
    a("    rte")
    a("")


def segments(a) -> None:
    a("hbl:")
    a("    addq.w  #1,d7")
    a("    move.w  d7,d0")
    a("    sub.w   #100,d0")
    a("    cmp.w   #64,d0")
    a("    bcs.s   range_a")
    a("    sub.w   #64,d0")
    a("    cmp.w   #64,d0")
    a("    bcc.w   out")
    a("    move.w  d0,d1               ; suffix: k NOPs")
    a("    moveq   #24,d0              ; prefix: 24 NOPs")
    a("    bra.s   go")
    a("range_a:")
    a("    moveq   #16,d1              ; suffix: 16 NOPs")
    a("go:")
    a("    add.w   d0,d0")
    a("    lea     slide1_end(pc),a1")
    a("    suba.w  d0,a1")
    a("    jmp     (a1)")
    nops(a, 4)
    a("slide1_end:")
    a("    move.b  #1,$ff8260          ; medium")
    a("    add.w   d1,d1")
    a("    lea     slide2_end(pc),a1")
    a("    suba.w  d1,a1")
    a("    jmp     (a1)")
    nops(a, 4)
    a("slide2_end:")
    a("    clr.b   $ff8260             ; low again")
    a("out:")
    a("    rte")
    a("")


for name, title, handler in (
    ("p35_midline_resolution.s", "P35: the resolution register written once on a line, at a clock that moves along the line.", sweeps),
    ("p45_midline_segments.s", "P45: a medium segment on a line, its start or its end moving along the line.", segments),
):
    open(os.path.join(here, name), "w", newline="\n").write(program(title, name, handler))
    print(name)
