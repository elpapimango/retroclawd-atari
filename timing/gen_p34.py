#!/usr/bin/env python3
"""Writes p34_blitter_timing.s: what a running Blitter costs the CPU, with HOG set and clear.

A counted loop runs in the main program; every VBL stores 8 bytes: the iterations of the frame just ended (long), the Blitter's
control byte ($FF8A3C, bit 7 busy), the MFP GPIP ($FFFA01) and two zero bytes. Six experiments, each started by the main loop
at its own frame (16 frames apart from frame 4) with the registers of a copy of `words` words from $30000 to $40000:
  H0..H3: HOG set, 20000 words, (HOP, OP) = (0, 0), (2, 3), (3, 1), (1, 5): the iterations lost in the frame show the clocks
          a word costs (the Internals table gives 1, 2, 3 and 2 nops a word);
  N0, N1: HOG clear, 100000 words, (2, 3) and (3, 1): the frames in which the busy bit stays set show how much of the bus the
          CPU keeps, the iterations in them what it runs.
Result at $C000: header 'P34', then 105 records of 8 bytes (frames 2 to 106). For a machine with a Blitter."""
import os

EXPERIMENTS = [
    # start frame, hop, op, control byte written (busy set), x count, y count
    (4, 0, 0, 0xC0, 200, 100),
    (20, 2, 3, 0xC0, 200, 100),
    (36, 3, 1, 0xC0, 200, 100),
    (52, 1, 5, 0xC0, 200, 100),
    (68, 2, 3, 0x80, 500, 200),
    (84, 3, 1, 0x80, 500, 200),
]
LAST_FRAME = 106


def source():
    L = [
        "; p34_blitter_timing.s (generated by gen_p34.py: do not edit)",
        "    .org $90000",
        "    move.w  #$2700,sr",
        "    clr.b   $fffa07",
        "    clr.b   $fffa09",
        "    clr.b   $fffa13",
        "    clr.b   $fffa15",
        "    lea     vbl(pc),a0",
        "    move.l  a0,$70",
        "    lea     $c000,a2",
        "    move.l  #$50333400,(a2)+",
        "    lea     table(pc),a4",
        "    lea     $ff8a00,a1",
        "    move.w  #$ffff,$28(a1)",
        "    move.w  #$ffff,$2a(a1)",
        "    move.w  #$ffff,$2c(a1)",
        "    move.w  #2,$20(a1)",
        "    move.w  #2,$22(a1)",
        "    move.w  #2,$2e(a1)",
        "    move.w  #2,$30(a1)",
        "    moveq   #0,d5",
        "    moveq   #0,d6",
        "    move.w  (a4),d7              ; the frame of the next start",
        "    move.w  #$2300,sr",
        "loop:",
        "    addq.l  #1,d5",
        "    cmp.w   d6,d7",
        "    bne.s   loop",
        "    ; start the experiment at (a4)",
        "    move.w  2(a4),d0             ; HOP high byte, OP low byte",
        "    move.b  d0,$3b(a1)",
        "    lsr.w   #8,d0",
        "    move.b  d0,$3a(a1)",
        "    move.l  #$30000,$24(a1)",
        "    move.l  #$40000,$32(a1)",
        "    move.w  6(a4),$36(a1)",
        "    move.w  8(a4),$38(a1)",
        "    move.b  #0,$3d(a1)",
        "    move.w  4(a4),d0",
        "    lea     10(a4),a4",
        "    move.w  (a4),d7",
        "    move.b  d0,$3c(a1)           ; start",
        "    bra.s   loop",
        "",
        "vbl:",
        "    addq.w  #1,d6",
        "    cmp.w   #2,d6",
        "    blt.s   clear",
        "    move.l  d5,(a2)+",
        "    move.b  $ff8a3c,(a2)+",
        "    move.b  $fffa01,(a2)+",
        "    clr.b   (a2)+",
        "    clr.b   (a2)+",
        f"    cmp.w   #{LAST_FRAME},d6",
        "    blt.s   clear",
        "    ori.w   #$0700,(sp)",
        "clear:",
        "    moveq   #0,d5",
        "    rte",
        "",
        "table:",
    ]
    for frame, hop, op, ctrl, x, y in EXPERIMENTS:
        L.append(f"    dc.w    {frame},${hop << 8 | op:04x},${ctrl:04x},{x},{y}")
    L.append("    dc.w    $7fff,0,0,0,0")
    L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p34_blitter_timing.s"), "w", newline="\n") as f:
        f.write(source())
    print(len(EXPERIMENTS), "experiments")
