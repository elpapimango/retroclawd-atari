#!/usr/bin/env python3
"""Writes p36_ste_io_cost.s: what a bus access to each STE register costs the CPU (the method of gen_p18.py).

A counted loop `addq.l #1,d5 ; <one access> ; bra.s` runs for 4 frames per variant; the VBL handler stores the count of
every frame and moves the interrupted program to the next variant. An access that makes the CPU wait shows as fewer
iterations in a frame.

Result at $C000: header 'P36', then per variant 3 longs (frames 2 to 4 of its run; the first frame after a switch is
not stored)."""
import os

VARIANTS = [
    ("nop", "nop"),
    ("shifter_palette_read", "move.w  $ff8240,d0"),
    ("ste_base_low_read", "move.b  $ff820d,d0"),
    ("ste_hscroll_write", "move.b  d4,$ff8265"),
    ("sound_ctrl_read", "move.b  $ff8901,d0"),
    ("sound_ctrl_write", "move.b  d4,$ff8901"),
    ("microwire_read", "move.w  $ff8922,d0"),
    ("microwire_mask_read", "move.w  $ff8924,d0"),
    ("joy_read", "move.w  $ff9200,d0"),
    ("joy_byte_read", "move.b  $ff9201,d0"),
    ("blitter_read", "move.b  $ff8a3c,d0"),
    ("blitter_halftone_read", "move.w  $ff8a00,d0"),
    ("blitter_halftone_write", "move.w  d4,$ff8a00"),
    ("rom_read", "move.w  $e00000,d0"),
    ("mw_read_to_mem", "move.w  $ff8922,(a1)"),
    ("mem_read_to_mem", "move.w  $20000,(a1)"),
    ("mw_read_postinc", "move.w  $ff8922,(a1)+\n    lea     -2(a1),a1"),
]
FRAMES_PER = 4


def source():
    n = len(VARIANTS)
    blocks = "\n".join(
        f"v{i}:                            ; {name}\n    addq.l  #1,d5\n    {insn}\n    bra.s   v{i}" for i, (name, insn) in enumerate(VARIANTS)
    )
    table = "\n".join(f"    dc.l    v{i}" for i in range(n))
    return f'''; p36_ste_io_cost.s: what a bus access to each I/O register costs the CPU.
; Generated by gen_p36.py: do not edit. See that file for what the probe records.
    .org $90000
    move.w  #$2700,sr
    clr.b   $fffa07             ; IERA, IERB, IMRA, IMRB: no MFP interrupt reaches the CPU
    clr.b   $fffa09
    clr.b   $fffa13
    clr.b   $fffa15
    lea     vbl(pc),a0
    move.l  a0,$70
    lea     $c000,a2
    move.l  #$50333600,(a2)+
    move.w  #$086,$ff8606       ; the FDC data register: accesses to it are harmless
    moveq   #$7f,d3
    add.w   #$7,d3              ; $86
    moveq   #0,d4
    lea     $20000,a1
    moveq   #0,d5
    moveq   #-1,d6              ; frame counter (the first VBL makes it 0)
    lea     table(pc),a3
    move.w  #$2300,sr
idle:
    bra.s   idle

vbl:
    addq.w  #1,d6
    move.w  d6,d0
    ext.l   d0
    divu    #{FRAMES_PER},d0     ; d0 low = variant, high = frame within it
    move.l  d0,d1
    swap    d1                  ; the frame within the variant
    cmp.w   #0,d1
    beq.s   switch
    move.l  d5,(a2)+
    bra.s   next
switch:
    cmp.w   #{n},d0
    bge.s   finish
    lsl.w   #2,d0
    move.l  (a3,d0.w),2(sp)     ; resume in the variant's loop
next:
    moveq   #0,d5
    rte
finish:
    ori.w   #$0700,(sp)
    bra.s   next

table:
{table}
{blocks}
'''


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p36_ste_io_cost.s"), "w", newline="\n") as f:
        f.write(source())
