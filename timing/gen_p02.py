#!/usr/bin/env python3
"""Writes p02_instruction_timing.s: P02, the clocks an instruction takes on the ST (wait states included).

For each variant a loop of four copies of one instruction runs while the HBL handler (every line, 512 clocks) stores
how many times the loop ran since the last HBL and starts again. After 64 lines the handler moves the interrupted PC to
the next variant. The pattern of the counts over the 64 lines fixes the loop's length in clocks to a fraction of a
clock, and the same program run in Hatari must leave the same counts. Result at $C000: 'P02' 0, one junk word (the first HBL), then one word a
line, 64 lines a variant, in the order of VARIANTS."""
import os

LINES = 64
COPIES = 4

# (name, body lines). Registers: d1 = 1, d2 = 7, d3 = 0; a0 = $20000 (RAM), a1 = $FC0100 (ROM), a3 = $FFFA01 (MFP, a
# byte register), a4 = $FF8240 (Shifter palette), a6 = $FF8800 (PSG).
VARIANTS = [
    ("nop", ["nop"]),
    ("moveq", ["moveq #1,d1"]),
    ("add.w d1,d2", ["add.w d1,d2"]),
    ("add.l d1,d2", ["add.l d1,d2"]),
    ("move.l d1,d2", ["move.l d1,d2"]),
    ("move.w (a0),d1", ["move.w (a0),d1"]),
    ("move.l (a0),d1", ["move.l (a0),d1"]),
    ("move.b (a0),d1", ["move.b (a0),d1"]),
    ("move.w d1,(a0)", ["move.w d1,(a0)"]),
    ("move.l d1,(a0)", ["move.l d1,(a0)"]),
    ("move.b d1,(a0)", ["move.b d1,(a0)"]),
    ("move.w (a1),d1 [ROM]", ["move.w (a1),d1"]),
    ("move.l (a1),d1 [ROM]", ["move.l (a1),d1"]),
    ("move.b (a3),d1 [MFP]", ["move.b (a3),d1"]),
    ("move.w (a4),d1 [palette]", ["move.w (a4),d1"]),
    ("move.w d1,(a4) [palette]", ["move.w d3,(a4)"]),
    ("move.b (a6),d1 [PSG]", ["move.b (a6),d1"]),
    ("move.b d1,(a6) [PSG]", ["move.b d3,(a6)"]),
    ("lsl.w #1,d1", ["lsl.w #1,d1"]),
    ("lsl.l #4,d1", ["lsl.l #4,d1"]),
    ("asr.w d2,d1", ["asr.w d2,d1"]),
    ("mulu d2,d1", ["mulu d2,d1"]),
    ("divu d2,d1", ["divu d2,d1"]),
    ("movem.l d1-d4,(a0)", ["movem.l d1-d4,(a0)"]),
    ("movem.l (a0),d1-d4", ["movem.l (a0),d1-d4"]),
    ("add.l (a0),d1", ["add.l (a0),d1"]),
    ("add.w d1,(a0)", ["add.w d1,(a0)"]),
    ("addq.w #1,(a0)", ["addq.w #1,(a0)"]),
    ("tst.w (a0)", ["tst.w (a0)"]),
    ("clr.w (a0)", ["clr.w (a0)"]),
    ("clr.l (a0)", ["clr.l (a0)"]),
    ("btst d2,d1", ["btst d2,d1"]),
    ("bset d2,d1", ["bset d2,d1"]),
    ("cmp.l d1,d2", ["cmp.l d1,d2"]),
    ("exg d1,d2", ["exg d1,d2"]),
    ("swap d1", ["swap d1"]),
    ("ext.l d1", ["ext.l d1"]),
    ("neg.l d1", ["neg.l d1"]),
    ("bsr/rts", ["bsr.s @sub", "bra.s @over", "@sub: rts", "@over:"]),
    ("beq.s not taken (+ nop)", ["beq.s @t", "nop", "@t:"]),
    ("bne.s taken (skips a nop)", ["bne.s @t", "nop", "@t:"]),
    ("lea 4(a0),a1", ["lea 4(a0),a1"]),
    ("move.w 4(a0),d1", ["move.w 4(a0),d1"]),
    ("move.l (a0,d3.w),d1", ["move.l (a0,d3.w),d1"]),
    ("move.w $2000.w,d1", ["move.w $2000.w,d1"]),
    ("move.w $20000.l,d1", ["move.w $20000.l,d1"]),
    ("move.l d1,-(a0)", ["move.l d1,-(a0)", "addq.l #4,a0"]),
    ("move.w (a0)+,d1", ["move.w (a0)+,d1", "subq.l #2,a0"]),
]


def source() -> str:
    out = []
    w = out.append
    w("; P02: the clocks an instruction takes on the ST (wait states included). Generated by gen_p02.py: do not edit.")
    w("; Each variant runs for one frame: the VBL handler restarts it (at the same point of every frame) and the HBL")
    w(f"; handler stores, for the first {LINES} lines, how many times the loop ran since the last HBL. Result at $C000: 'P02' 0,")
    w(f"; then {LINES} words a variant, in this order:")
    for i, (name, _) in enumerate(VARIANTS):
        w(f";   {i:2d}  {name}")
    w("    .org $90000")
    w("    move.w  #$2700,sr")
    w("    clr.b   $fffa07             ; IERA, IERB, IMRA, IMRB: no MFP interrupt reaches the CPU")
    w("    clr.b   $fffa09")
    w("    clr.b   $fffa13")
    w("    clr.b   $fffa15")
    w("    lea     hbl(pc),a0")
    w("    move.l  a0,$68")
    w("    lea     vbl(pc),a0")
    w("    move.l  a0,$70")
    w("    lea     $c000,a2")
    w("    move.l  #$50303200,(a2)+    ; \"P02\" 0")
    w("    lea     table(pc),a5")
    w("    moveq   #0,d0               ; loop runs since the last HBL")
    w(f"    move.w  #{LINES + 1},d5            ; lines since the VBL (more than recorded: nothing is stored yet)")
    w("    moveq   #-4,d7              ; byte offset of the variant in the table")
    w("    moveq   #1,d1")
    w("    moveq   #7,d2")
    w("    moveq   #0,d3")
    w("    lea     $20000,a0")
    w("    lea     $fc0100,a1")
    w("    lea     $fffa01,a3")
    w("    lea     $ff8240,a4")
    w("    lea     $ff8800,a6")
    w("    move.w  #$2100,sr           ; HBL (2) and VBL (4) may interrupt")
    w("idle:")
    w("    stop    #$2100")
    w("    bra.s   idle")
    w("")
    w("vbl:")
    w("    move.w  #$2100,(sp)         ; HBL and VBL may interrupt whatever runs next")
    w("    moveq   #0,d0")
    w("    moveq   #0,d5")
    w("    addq.w  #4,d7")
    w(f"    cmp.w   #{4 * len(VARIANTS)},d7")
    w("    bne.s   next_variant")
    w("    ori.w   #$0700,(sp)         ; every variant has run: mask every interrupt")
    w("    subq.w  #4,d7")
    w("    rte")
    w("next_variant:")
    w("    move.l  0(a5,d7.w),2(sp)    ; the stacked PC: the variant starts at the same point after every VBL")
    w("    rte")
    w("")
    w("hbl:")
    w("    addq.w  #1,d5")
    w(f"    cmp.w   #{LINES + 1},d5")
    w("    bge.s   hbl_done")
    w("    move.w  d0,(a2)+")
    w("hbl_done:")
    w("    moveq   #0,d0")
    w("    rte")
    w("")
    for i, (name, body) in enumerate(VARIANTS):
        w(f"v{i}:                             ; {name}")
        for c in range(COPIES):
            for line in body:
                line = line.replace("@sub", f"s{i}_{c}").replace("@over", f"o{i}_{c}").replace("@t", f"t{i}_{c}")
                if ":" in line and not line.startswith(" "):
                    label, _, rest = line.partition(":")
                    w(f"{label.strip()}:")
                    if rest.strip():
                        w(f"    {rest.strip()}")
                else:
                    w(f"    {line}")
        w("    addq.w  #1,d0")
        w(f"    bra.w   v{i}")
        w("")
    w("table:")
    for i in range(len(VARIANTS)):
        w(f"    dc.l    v{i}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p02_instruction_timing.s"), "w", newline="\n") as f:
        f.write(source())
