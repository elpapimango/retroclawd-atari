#!/usr/bin/env python3
"""Writes p27_ste_video_regs.s: write and read back the STE Shifter's registers.

For each byte register (video base high/mid/low, line offset, pixel scroll and its no-prefetch twin, the video counter's three
bytes, sync mode, resolution) the values in VALUES are written one after the other, and after each the register is read
back as a byte. The palette word at $FF8240 gets WORDS written (read back as a word) and then BYTES written to its high and
low bytes (read back as a word).

Result at $C000: header 'P27', then for each byte register len(VALUES) bytes, then the palette words (2 bytes each).
It is meant for an STE (Hatari --machine ste); on an ST the registers do not exist."""
import os

VALUES = [0x00, 0xFF, 0x5A, 0xA5, 0x01, 0x80, 0x7F, 0x0F]
REGS = [0x8201, 0x8203, 0x820D, 0x820F, 0x8264, 0x8265, 0x820A, 0x8260]
COUNTER = [0x8205, 0x8207, 0x8209]
WORDS = [0x0000, 0xFFFF, 0x0555, 0x0AAA, 0x0808, 0x0777, 0x0FFF, 0x1234, 0x0008, 0x0800]
BYTES = [(0x8240, 0xFF), (0x8241, 0xFF), (0x8240, 0x0A), (0x8241, 0x05), (0x8241, 0x08)]


def source():
    lines = [
        "; p27_ste_video_regs.s: write and read back the STE Shifter's registers (generated by gen_p27.py: do not edit).",
        "    .org $90000",
        "    move.w  #$2700,sr",
        "    lea     $c000,a2",
        "    move.l  #$50323700,(a2)+",
        "    move.b  $ff8201,d6          ; keep the screen base the system set",
        "    move.b  $ff8203,d7",
    ]
    for addr in REGS + COUNTER:
        for v in VALUES:
            lines.append(f"    move.b  #${v:02x},${0xFF0000 | addr:06x}")
            lines.append(f"    move.b  ${0xFF0000 | addr:06x},(a2)+")
    for w in WORDS:
        lines.append(f"    move.w  #${w:04x},$ff8240")
        lines.append("    move.w  $ff8240,(a2)+")
    for addr, v in BYTES:
        lines.append(f"    move.b  #${v:02x},${0xFF0000 | addr:06x}")
        lines.append("    move.w  $ff8240,(a2)+")
    lines += ["    move.b  d6,$ff8201", "    move.b  d7,$ff8203", "done:", "    bra.s   done", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p27_ste_video_regs.s"), "w", newline="\n") as f:
        f.write(source())
