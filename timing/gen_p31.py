#!/usr/bin/env python3
"""Writes p31_ste_ports.s: the STE's enhanced joystick ports at rest, and what writing their registers does.

Result at $C000: header 'P31', then for each write pattern ($FFFF, $0000, $A5A5 in turn, written as a word to $FF9200 and to
$FF9202 first; the first row writes nothing): the words at $FF9200 and $FF9202, the words at $FF9210, 12, 14, 16, 20, 22 (6 words), then the bytes at
$FF9201, 03, 11, 13, 15, 17: 2+2+12+6 = 22 bytes a row, 4 rows. (The addresses $FF9218-$FF921F, $FF9221, $FF9223 and
above $FF9223 bus-error in Hatari, found with scan_p31.py.)
For a machine with the STE ports (Hatari --machine ste)."""
import os


def rows():
    return [None, 0xFFFF, 0x0000, 0xA5A5]


def source():
    L = [
        "; p31_ste_ports.s (generated by gen_p31.py: do not edit)",
        "    .org $90000",
        "    move.w  #$2700,sr",
        "    clr.b   $fffa07",
        "    clr.b   $fffa09",
        "    clr.b   $fffa13",
        "    clr.b   $fffa15",
        "    lea     $c000,a2",
        "    move.l  #$50333100,(a2)+",
        "    lea     $ff9200,a3",
    ]
    for v in rows():
        if v is not None:
            L.append(f"    move.w  #${v:04x},(a3)")
            L.append(f"    move.w  #${v:04x},$02(a3)")
        L += [
            "    move.w  (a3),(a2)+",
            "    move.w  $02(a3),(a2)+",
        ]
        for off in (0x10, 0x12, 0x14, 0x16, 0x20, 0x22):
            L.append(f"    move.w  ${off:02x}(a3),(a2)+")
        for off in (0x01, 0x03, 0x11, 0x13, 0x15, 0x17):
            L.append(f"    move.b  ${off:02x}(a3),(a2)+")
    L += ["done:", "    bra.s   done", ""]
    return "\n".join(L)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p31_ste_ports.s"), "w", newline="\n") as f:
        f.write(source())
    print("p31")
