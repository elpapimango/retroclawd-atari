#!/usr/bin/env python3
"""Writes p30_microwire.s: how the STE's Microwire data register behaves after a write.

A mask ($FF8924) and data ($FF8922) word are written and the data register is read 20 times in a row with PAD NOPs between
the reads, for PADS = 0, 4, 12; then the mask register is read 8 times. The three experiments are repeated for two data/mask
pairs. Result at $C000: header 'P30', then per experiment 20 data words and 8 mask words (56 bytes), six experiments.
For an STE (Hatari --machine ste)."""
import os

PADS = [0, 4, 12]
PAIRS = [(0x07FF, 0x09D1), (0x0FFE, 0x0AA9)]


def source():
    L = [
        "; p30_microwire.s (generated by gen_p30.py: do not edit)",
        "    .org $90000",
        "    move.w  #$2700,sr",
        "    lea     $c000,a2",
        "    move.l  #$50333000,(a2)+",
    ]
    for mask, data in PAIRS:
        for pad in PADS:
            L.append(f"    move.w  #${mask:04x},$ff8924")
            L.append(f"    move.w  #${data:04x},$ff8922")
            L.append("    moveq   #19,d7")
            lab = f"d_{mask:04x}_{pad}"
            L.append(f"{lab}:")
            L.append("    move.w  $ff8922,(a2)+")
            L.extend(["    nop"] * pad)
            L.append(f"    dbra    d7,{lab}")
            L.append("    moveq   #7,d7")
            lab2 = f"m_{mask:04x}_{pad}"
            L.append(f"{lab2}:")
            L.append("    move.w  $ff8924,(a2)+")
            L.append(f"    dbra    d7,{lab2}")
            # let any transfer finish before the next experiment
            L.append("    move.w  #3000,d6")
            L.append(f"w_{mask:04x}_{pad}:")
            L.append(f"    dbra    d6,w_{mask:04x}_{pad}")
    L += ["done:", "    bra.s   done", ""]
    return "\n".join(L)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p30_microwire.s"), "w", newline="\n") as f:
        f.write(source())
