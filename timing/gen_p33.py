#!/usr/bin/env python3
"""Writes p33_blitter_sweep.s: what the Blitter leaves in memory, for a sweep of its settings.

A table gives each case: the halftone and logical operation, the skew byte, the control byte (line number and smudge), the
source and destination increments, the three end masks, the counts and where in the 256-word areas the blit starts. For each
case the program fills the source area ($30000) and the destination area ($40000) with a pseudo-random pattern, loads the
registers, starts the Blitter with HOG set and waits until Busy is clear, then stores a checksum of the destination area and the
registers the Blitter leaves (source address, destination address, counts, control).

Result at $C000: header 'P33', then 20 bytes a case: checksum (long), source address (long), destination address (long), x count
(word), y count (word), control byte and padding (word). For a machine with a Blitter (Hatari --machine ste or megast)."""
import os
import random

HALFTONE = [0x8001, 0x4002, 0x2004, 0x1008, 0x0810, 0x0420, 0x0240, 0x0180, 0xF00F, 0xE11E, 0xD22D, 0xC33C, 0xB44B, 0xA55A, 0x9669, 0x8778]


def case(hop=2, op=3, skew=0, ctrl=0, sx=2, sy=8, dx=2, dy=8, m1=0xFFFF, m2=0xFFFF, m3=0xFFFF, xc=3, yc=4, so=64, do=64):
    return (hop, op, skew, ctrl, sx, sy, dx, dy, m1, m2, m3, xc, yc, so, do)


def cases():
    out = []
    # every halftone and logical operation on plain geometry
    for hop in range(4):
        for op in range(16):
            out.append(case(hop=hop, op=op))
    # end masks against the word count
    for xc in (1, 2, 3, 5):
        out.append(case(m1=0x0FFF, m2=0xAAAA, m3=0xFFF0, xc=xc))
        out.append(case(m1=0x00FF, m2=0x5555, m3=0xFF00, xc=xc, op=6))
    # skew with the forced and the skipped source read
    for skew in range(16):
        for flags in (0x00, 0x40, 0x80, 0xC0):
            out.append(case(skew=skew | flags, xc=3, m1=0x3FFF, m3=0xFFFC))
    # negative increments: the blit runs backwards from the end of the area
    for skew in (0, 3, 9):
        for flags in (0x00, 0x80):
            out.append(case(skew=skew | flags, sx=-2, dx=-2, so=130, do=130, m1=0x7FFF, m3=0xFFFE))
    # increments other than 2, source and destination apart
    out.append(case(sx=4, dx=2, xc=3))
    out.append(case(sx=0, dx=2, xc=3))
    out.append(case(sx=2, dx=6, xc=3, sy=-8, dy=-8, so=120, do=120))
    out.append(case(sx=2, dx=2, sy=0, dy=0, yc=4))
    out.append(case(yc=1, xc=1))
    out.append(case(yc=16, xc=2, sy=4, dy=4))
    # the halftone line number and smudge
    for line in range(16):
        out.append(case(hop=1, op=3, ctrl=line, yc=6))
    for line in (0, 5, 15):
        out.append(case(hop=1, op=3, ctrl=0x20 | line, yc=6, skew=3))
        out.append(case(hop=2, op=3, ctrl=0x20 | line, yc=6, skew=0x80 | 5, xc=3))
    # a negative y increment on the destination steps the halftone line down
    out.append(case(hop=1, op=3, ctrl=7, yc=6, dy=-8, do=120))
    out.append(case(hop=3, op=3, ctrl=2, yc=6, dy=-8, do=120, skew=5))
    # source and destination overlap
    out.append(case(sx=2, dx=2, so=64, do=66, op=3))
    out.append(case(sx=-2, dx=-2, so=130, do=128, op=3))
    return out


def source(cs=None, raw=False, name="p33"):
    cs = cs if cs is not None else cases()
    L = [
        "; p33_blitter_sweep.s (generated by gen_p33.py: do not edit)",
        "    .org $90000",
        "    move.w  #$2700,sr",
        "    clr.b   $fffa07             ; no MFP interrupt reaches the CPU",
        "    clr.b   $fffa09",
        "    clr.b   $fffa13",
        "    clr.b   $fffa15",
        "    lea     $c000,a2",
        f"    move.l  #${0x50000000 | ord(name[1]) << 16 | ord(name[2]) << 8:08x},(a2)+",
        "    lea     cases(pc),a4",
        f"    move.w  #{len(cs) - 1},d7",
        "case:",
        "    lea     $30000,a5",
        "    move.w  #$1234,d0",
        "    bsr.w   fill",
        "    lea     $40000,a5",
        "    move.w  #$5678,d0",
        "    bsr.w   fill",
        "    lea     halftone(pc),a0",
        "    lea     $ff8a00,a1",
        "    moveq   #15,d1",
        "ht:",
        "    move.w  (a0)+,(a1)+",
        "    dbra    d1,ht",
        "    lea     $ff8a00,a1",
        "    move.w  (a4)+,d0            ; halftone operation (high byte), logical operation (low byte)",
        "    move.b  d0,$3b(a1)",
        "    lsr.w   #8,d0",
        "    move.b  d0,$3a(a1)",
        "    move.w  (a4)+,d3            ; skew (high byte), control (low byte)",
        "    move.w  d3,d6",
        "    lsr.w   #8,d3",
        "    move.b  d3,$3d(a1)",
        "    move.w  (a4)+,$20(a1)       ; source x increment",
        "    move.w  (a4)+,$22(a1)       ; source y increment",
        "    move.w  (a4)+,$2e(a1)       ; destination x increment",
        "    move.w  (a4)+,$30(a1)       ; destination y increment",
        "    move.w  (a4)+,$28(a1)       ; left end mask",
        "    move.w  (a4)+,$2a(a1)       ; middle mask",
        "    move.w  (a4)+,$2c(a1)       ; right end mask",
        "    move.w  (a4)+,$36(a1)       ; x count",
        "    move.w  (a4)+,$38(a1)       ; y count",
        "    moveq   #0,d0",
        "    move.w  (a4)+,d0            ; where the source starts, in words",
        "    add.l   d0,d0",
        "    add.l   #$30000,d0",
        "    move.l  d0,$24(a1)",
        "    moveq   #0,d0",
        "    move.w  (a4)+,d0            ; where the destination starts, in words",
        "    add.l   d0,d0",
        "    add.l   #$40000,d0",
        "    move.l  d0,$32(a1)",
        "    and.b   #$3f,d6             ; the line number and smudge of the case, HOG and Busy set to start",
        "    or.b    #$c0,d6",
        "    move.b  d6,$3c(a1)",
        "wait:",
        "    btst    #7,$3c(a1)",
        "    bne.s   wait",
    ] + ([
        f"    lea     $40000+{2 * (64 if raw is True else raw)},a5",
        "    moveq   #39,d1",
        "dump:",
        "    move.w  (a5)+,(a2)+",
        "    dbra    d1,dump",
    ] if raw else [
        "    ; the checksum of the destination area",
        "    lea     $40000,a5",
        "    moveq   #0,d0",
        "    move.w  #255,d1",
        "sum:",
        "    move.w  (a5)+,d2",
        "    rol.l   #3,d0",
        "    add.w   d2,d0",
        "    dbra    d1,sum",
        "    move.l  d0,(a2)+",
        "    move.l  $24(a1),(a2)+",
        "    move.l  $32(a1),(a2)+",
        "    move.w  $36(a1),(a2)+",
        "    move.w  $38(a1),(a2)+",
        "    move.b  $3c(a1),(a2)+",
        "    move.b  #0,(a2)+",
    ]) + [
        "    dbra    d7,case",
        "done:",
        "    bra.s   done",
        "",
        "fill:                           ; 256 pseudo-random words at a5, seed d0",
        "    move.w  #255,d1",
        "f1:",
        "    mulu    #25173,d0",
        "    add.w   #13849,d0",
        "    move.w  d0,(a5)+",
        "    dbra    d1,f1",
        "    rts",
        "",
        "halftone:",
        "    dc.w    " + ",".join(f"${w:04x}" for w in HALFTONE),
        "",
        "cases:",
    ]
    for (hop, op, skew, ctrl, sx, sy, dx, dy, m1, m2, m3, xc, yc, so, do) in cs:
        w = lambda v: f"${v & 0xFFFF:04x}"
        L.append("    dc.w    " + ",".join([w(hop << 8 | op), w(skew << 8 | ctrl), w(sx), w(sy), w(dx), w(dy), w(m1), w(m2), w(m3), w(xc), w(yc), w(so), w(do)]))
    L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p33_blitter_sweep.s"), "w", newline="\n") as f:
        f.write(source())
    print(len(cases()), "cases")
