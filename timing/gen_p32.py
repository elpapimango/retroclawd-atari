#!/usr/bin/env python3
"""Writes p32_rtc.s: the Mega ST's RP5C15 clock registers, written and read back in both banks.

Result at $C000: header 'P32', then for bank 0 and bank 1 (the mode register $FFFC3B written 0 and 1): for each of the registers
0 to 12, 14 and 15 (at $FFFC21 + 2n) the byte read after writing $0F, $00 and $05 (45 bytes, three padding bytes: 48), then the
byte read back from the mode register after writing 0 to 15 in turn (16 bytes). The bank 0 time registers follow the host's
clock in Hatari: their values are not compared. For a machine with the clock (Hatari --machine megast)."""
import os

REGS = list(range(13)) + [14, 15]


def source():
    L = [
        "; p32_rtc.s (generated by gen_p32.py: do not edit)",
        "    .org $90000",
        "    move.w  #$2700,sr",
        "    clr.b   $fffa07",
        "    clr.b   $fffa09",
        "    clr.b   $fffa13",
        "    clr.b   $fffa15",
        "    lea     $c000,a2",
        "    move.l  #$50333200,(a2)+",
        "    lea     $fffc20,a3",
    ]
    for bank in (0, 1):
        L.append(f"    move.b  #{bank},$1b(a3)")
        for r in REGS:
            for v in (0x0F, 0x00, 0x05):
                L.append(f"    move.b  #{v},${2 * r + 1:02x}(a3)")
                L.append(f"    move.b  ${2 * r + 1:02x}(a3),(a2)+")
        for _ in range(3):
            L.append("    move.b  #0,(a2)+")
    L.append("    move.b  #0,$1b(a3)")
    for v in range(16):
        L.append(f"    move.b  #{v},$1b(a3)")
        L.append("    move.b  $1b(a3),(a2)+")
    L += ["    move.b  #0,$1b(a3)", "done:", "    bra.s   done", ""]
    return "\n".join(L)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p32_rtc.s"), "w", newline="\n") as f:
        f.write(source())
    print("p32")
