#!/usr/bin/env python3
"""Writes p09_border_left.s, p10_border_right.s and p11_border_control.s: sweeps of two register writes along a line.

On the target line the HBL handler runs a NOP slide whose length grows by 4 clocks each frame (128 frames, 0 to 508
clocks), writes VALUE1 to REG, VALUE2 to REG again (one instruction apart), then reads the video address counter.  The counter says how many bytes the Shifter has fetched by then: a
line whose border opened fetches more than 160 bytes. The control probe writes the value the register already has, so
its counters are what a line fetches without a trick at the same moments.

Result at $C000: header, then per frame 4 bytes: the frame (1 to 128) and the counter high/mid/low at the entry of the
HBL handler of line + 2, where every handler is short and the extra bytes the trick made the Shifter fetch are all in."""
import os

NOPS = 128
LINE = 100
FRAMES = 128

VARIANTS = [
    # file, probe name, register, value1, value2, what
    ("p09_border_left.s", "P09", "$ff8260", 2, 0, "resolution: high then low (the left border)"),
    ("p10_border_right.s", "P10", "$ff820a", 0, 2, "sync mode: 60 Hz then 50 Hz (the right border)"),
    ("p11_border_control.s", "P11", "$ff820a", 2, 2, "sync mode written with its own value (no trick)"),
]


def nops(n):
    return "\n".join("    dc.w    " + ",".join(["$4E71"] * min(16, n - i)) for i in range(0, n, 16))


def source(name, reg, v1, v2, what):
    return f'''; {name}: {what}.
; Generated by gen_p09.py: do not edit. See that file for what the probe records.
    .org $90000
    move.w  #$2700,sr
    clr.b   $fffa07             ; IERA, IERB, IMRA, IMRB: no MFP interrupt reaches the CPU
    clr.b   $fffa09
    clr.b   $fffa13
    clr.b   $fffa15
    lea     hbl(pc),a0
    move.l  a0,$68
    lea     vbl(pc),a0
    move.l  a0,$70
    lea     $c000,a2
    move.l  #$50{ord(name[1]):02X}{ord(name[2]):02X}00,(a2)+
    moveq   #0,d6               ; frames
    moveq   #0,d7               ; lines since the VBL
    lea     slide_end(pc),a1
    lea     {reg},a3
    moveq   #{v1},d4
    moveq   #{v2},d5
    move.w  #$2100,sr
idle:
    stop    #$2100
    bra.s   idle

vbl:
    move.w  #$2100,(sp)
    addq.w  #1,d6
    moveq   #0,d7
    move.w  d6,d0
    subq.w  #1,d0
    and.w   #127,d0             ; this frame's step: 4 clocks a step, counted back from the end of the slide
    add.w   d0,d0
    lea     slide_end(pc),a1
    suba.w  d0,a1
    cmp.w   #{FRAMES + 1},d6
    bne.s   vbl_done
    ori.w   #$0700,(sp)         ; the frames are done: mask every interrupt
vbl_done:
    rte

hbl:
    addq.w  #1,d7
    cmp.w   #{LINE},d7
    beq.s   target
    cmp.w   #{LINE + 2},d7
    beq.w   next
    rte
target:
    jmp     (a1)
slide:                          ; {NOPS} NOPs
{nops(NOPS)}
slide_end:
    move.b  d4,(a3)             ; VALUE1 to the register (8 clocks), then VALUE2 (8 clocks)
    move.b  d5,(a3)
    rte
next:
    move.b  d6,(a2)+
    move.b  $ff8205,(a2)+
    move.b  $ff8207,(a2)+
    move.b  $ff8209,(a2)+
    rte
'''


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    for fname, name, reg, v1, v2, what in VARIANTS:
        with open(os.path.join(here, fname), "w", newline="\n") as f:
            f.write(source(name, reg, v1, v2, what))
