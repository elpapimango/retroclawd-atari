#!/usr/bin/env python3
"""Writes p12_border_vertical.s and p13_border_vertical_control.s: where in the frame a 60 Hz line removes the top or bottom border.

For frame f (0 to 255) the HBL handler writes the sync mode register to 60 Hz at the entry of line X = 10 + f and back to
50 Hz at the entry of the next line (the control probe writes 50 Hz both times). The video address counter is read at the
entry of lines 120 and 300 of the same frame: a border that opened fetches more lines by then, and the counter shows it.

Result at $C000: header, then per frame 7 bytes: the frame (1 to 256), the counter (high, mid, low) at line 120, the counter
at line 300."""
import os

FRAMES = 256

VARIANTS = [
    ("p12_border_vertical.s", "P12", 0, "60 Hz on line 10 + frame"),
    ("p13_border_vertical_control.s", "P13", 2, "50 Hz written twice (no trick)"),
]


def source(name, v60, what):
    return f'''; {name}: {what}.
; Generated by gen_p12.py: do not edit. See that file for what the probe records.
    .org $90000
    move.w  #$2700,sr
    clr.b   $fffa07             ; IERA, IERB, IMRA, IMRB: no MFP interrupt reaches the CPU
    clr.b   $fffa09
    clr.b   $fffa13
    clr.b   $fffa15
    lea     hbl(pc),a0
    move.l  a0,$68
    lea     vbl(pc),a0
    move.l  a0,$70
    lea     $c000,a2
    move.l  #$50{ord(name[1]):02X}{ord(name[2]):02X}00,(a2)+
    lea     $ff820a,a3
    moveq   #{v60},d4           ; the value written on line X
    moveq   #2,d5               ; 50 Hz
    moveq   #0,d6               ; frames
    move.w  #-1000,d7           ; lines since the VBL (nothing is done before the first one)
    moveq   #0,d3               ; X for this frame
    move.w  #$2100,sr
idle:
    stop    #$2100
    bra.s   idle

vbl:
    move.w  #$2100,(sp)
    addq.w  #1,d6
    moveq   #0,d7
    move.w  d6,d3
    add.w   #9,d3               ; X = 10 + (d6 - 1)
    move.w  d6,d0
    subq.w  #1,d0
    move.w  d0,d1
    lsl.w   #3,d0
    sub.w   d1,d0               ; 7 bytes a frame
    lea     $c004,a2
    adda.w  d0,a2
    cmp.w   #{FRAMES + 1},d6
    bne.s   vbl_done
    ori.w   #$0700,(sp)         ; the frames are done: mask every interrupt
vbl_done:
    rte

hbl:
    addq.w  #1,d7
    cmp.w   d3,d7
    beq.s   on
    move.w  d3,d0
    addq.w  #1,d0
    cmp.w   d0,d7
    beq.s   off
    cmp.w   #120,d7
    beq.s   read120
    cmp.w   #300,d7
    beq.s   read300
    rte
on:
    move.b  d4,(a3)
    rte
off:
    move.b  d5,(a3)
    rte
read120:
    move.b  d6,(a2)
    move.b  $ff8205,1(a2)
    move.b  $ff8207,2(a2)
    move.b  $ff8209,3(a2)
    rte
read300:
    move.b  $ff8205,4(a2)
    move.b  $ff8207,5(a2)
    move.b  $ff8209,6(a2)
    rte
'''


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    for fname, name, v60, what in VARIANTS:
        with open(os.path.join(here, fname), "w", newline="\n") as f:
            f.write(source(name, v60, what))
