#!/usr/bin/env python3
"""Writes p29_ste_dma_sound.s: the STE's DMA sound registers and how the playback counter moves.

Result at $C000: header 'P29', then
  - 48 bytes of register read-back: for each of 11 registers ($FF8901, 03, 05, 07, 09, 0B, 0D, 0F, 11, 13, $FF8921) the byte
    read after writing $FF, $00 and $A5 (33 bytes), then the bytes read at the even addresses $FF8900 to $FF8914 (11 bytes),
    padded;
  - eight experiments (rate 0 to 3, mono then stereo) of 32 records: play once over 64 KB from $20000 and sample;
  - the same at 50 kHz mono over a frame of 64 bytes (the end of a frame, play once);
  - the same in loop mode;
  - the same in loop mode over a frame of 16 bytes with MFP timer A counting events: 32 records, then the timer A data byte.
A record is 6 bytes: the counter ($FF8909, 0B, 0D) and the frame end's high byte ($FF890F) read by one MOVEP.L, the control
register $FF8901, the MFP's GPIP $FFFA01. Records are taken 64 loop iterations (about 650 clocks) apart.
For a machine with DMA sound (Hatari --machine ste)."""
import os

REGS = [0x01, 0x03, 0x05, 0x07, 0x09, 0x0B, 0x0D, 0x0F, 0x11, 0x13, 0x21]
GAP = 64
RECORDS = 32


def source():
    L = [
        "; p29_ste_dma_sound.s (generated by gen_p29.py: do not edit)",
        "    .org $90000",
        "    move.w  #$2700,sr",
        "    clr.b   $fffa07             ; no MFP interrupt reaches the CPU",
        "    clr.b   $fffa09",
        "    clr.b   $fffa13",
        "    clr.b   $fffa15",
        "    lea     $c000,a2",
        "    move.l  #$50323900,(a2)+",
        "    lea     $ff8900,a3",
        "    lea     $ff8909,a4",
        "    clr.b   $01(a3)             ; stop the DMA",
        "    ; register read-back",
    ]
    for r in REGS:
        for v in (0xFF, 0x00, 0xA5):
            L.append(f"    move.b  #${v:02x},${r:02x}(a3)")
            L.append(f"    move.b  ${r:02x}(a3),(a2)+")
    for r in range(0, 0x16, 2):
        L.append(f"    move.b  ${r:02x}(a3),(a2)+")
    L.append("    moveq   #0,d0")
    for _ in range(4):
        L.append("    move.b  d0,(a2)+")
    # eight rate experiments
    for stereo in (0, 0x80):
        for rate in range(4):
            L += setup(0x20000, 0x30000, rate | stereo, 1)
            L.append("    bsr.w   samp")
    # the end of a frame, play once
    L += setup(0x20000, 0x20040, 3, 1)
    L.append("    bsr.w   samp")
    # loop mode
    L += setup(0x20000, 0x20040, 3, 3)
    L.append("    bsr.w   samp")
    # timer A counting the frame ends in loop mode over 16 bytes
    L += [
        "    clr.b   $fffa19             ; timer A stopped",
        "    move.b  #$ff,$fffa1f        ; data",
        "    move.b  #$08,$fffa19        ; event count mode",
    ]
    L += setup(0x20000, 0x20010, 3, 3)
    L.append("    bsr.w   samp")
    L += [
        "    move.b  $fffa1f,(a2)+",
        "    clr.b   $01(a3)",
        "    clr.b   $fffa19",
        "done:",
        "    bra.s   done",
        "",
        "samp:",
        f"    moveq   #{RECORDS - 1},d6",
        "rl:",
        f"    move.w  #{GAP},d5",
        "w:",
        "    dbra    d5,w",
        "    movep.l 0(a4),d0",
        "    move.l  d0,(a2)+",
        "    move.b  $01(a3),(a2)+",
        "    move.b  $fffa01,(a2)+",
        "    dbra    d6,rl",
        "    clr.b   $01(a3)             ; stop",
        "    rts",
        "",
    ]
    return "\n".join(L)


def setup(base, end, mode, control):
    """Stop, program the frame and the mode, start with `control` in $FF8901."""
    out = ["    clr.b   $01(a3)"]
    out += [
        f"    move.b  #${(base >> 16) & 0xFF:02x},$03(a3)",
        f"    move.b  #${(base >> 8) & 0xFF:02x},$05(a3)",
        f"    move.b  #${base & 0xFF:02x},$07(a3)",
        f"    move.b  #${(end >> 16) & 0xFF:02x},$0f(a3)",
        f"    move.b  #${(end >> 8) & 0xFF:02x},$11(a3)",
        f"    move.b  #${end & 0xFF:02x},$13(a3)",
        f"    move.b  #${mode:02x},$21(a3)",
        f"    move.b  #${control:02x},$01(a3)",
    ]
    return out


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p29_ste_dma_sound.s"), "w", newline="\n") as f:
        f.write(source())
    print("p29")
