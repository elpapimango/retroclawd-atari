#!/usr/bin/env python3
"""Writes p41_ste_sound_rate.s: the DMA sound's byte rate over a long run, to fit the rate against the CPU clock.

For each of five modes (rate 0 to 3 mono, rate 3 stereo) the DMA plays in loop mode over a 64 KB frame from $20000 while the CPU
counts 300000 iterations of SUBQ.L/BNE; then the counter ($FF8909/0B/0D) and the frame end's high byte are read with one MOVEP.L.
Result at $C000: header 'P41', then 4 bytes a mode (the counter's three bytes and the end's high byte)."""
import os

import gen_p29


def source():
    L = [
        "; p41_ste_sound_rate.s (generated by gen_p41.py: do not edit)",
        "    .org $90000",
        "    move.w  #$2700,sr",
        "    clr.b   $fffa07",
        "    clr.b   $fffa09",
        "    clr.b   $fffa13",
        "    clr.b   $fffa15",
        "    lea     $c000,a2",
        "    move.l  #$50343100,(a2)+",
        "    lea     $ff8900,a3",
        "    lea     $ff8909,a4",
    ]
    for mode in (0, 1, 2, 3, 0x83):
        L += gen_p29.setup(0x20000, 0x30000, mode, 3)
        L += [
            "    move.l  #300000,d5",
            "w%d:" % mode,
            "    subq.l  #1,d5",
            "    bne.s   w%d" % mode,
            "    movep.l 0(a4),d0",
            "    move.l  d0,(a2)+",
            "    clr.b   $01(a3)",
        ]
    L += ["done:", "    bra.s   done", ""]
    return "\n".join(L)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p41_ste_sound_rate.s"), "w", newline="\n") as f:
        f.write(source())
    print("p41")
