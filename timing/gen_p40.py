#!/usr/bin/env python3
"""Writes p40_blitter_restart.s: what a second start does when the Y count has run down to zero.

EmuTOS starts its blits with a write and restarts them with a TAS of the control register ($FF8A3C), which after the blit has
ended writes the busy bit again with the registers as the first blit left them (Y count 0). The probe records, for the
experiments, the Y count, the destination address, the control byte and the word the blit writes: 1) a one-line blit that
writes zero, 2) the same registers with only the operation changed to all-ones and the busy bit written again, 3) the same
with a TAS after the word is set back. If a start with a Y count of 0 ran 65536 lines the destination address would be
$60000 afterwards (the lines step 2 bytes).

Result at $C000: header 'P40', then 10 bytes an experiment: Y count (word), destination address (long), control (word, byte
in the high half), the word at $40000. For a machine with a Blitter (Hatari --machine ste or megast)."""
import os


def source():
    L = [
        "; p40_blitter_restart.s (generated by gen_p40.py: do not edit)",
        "    .org $90000",
        "    move.w  #$2700,sr",
        "    clr.b   $fffa07",
        "    clr.b   $fffa09",
        "    clr.b   $fffa13",
        "    clr.b   $fffa15",
        "    lea     $c000,a2",
        "    move.l  #$50343000,(a2)+",
        "    lea     $ff8a00,a1",
        "    move.w  #$1234,$40000",
        "    move.w  #2,$2e(a1)          ; destination x and y increments",
        "    move.w  #2,$30(a1)",
        "    move.w  #$ffff,$28(a1)",
        "    move.w  #$ffff,$2a(a1)",
        "    move.w  #$ffff,$2c(a1)",
        "    move.l  #$40000,$32(a1)",
        "    move.w  #1,$36(a1)",
        "    move.w  #1,$38(a1)",
        "    move.b  #0,$3a(a1)          ; HOP 0 (ones), OP 0 (zero)",
        "    move.b  #0,$3b(a1)",
        "    move.b  #0,$3d(a1)",
        "    move.b  #$80,$3c(a1)",
        "w1:",
        "    btst    #7,$3c(a1)",
        "    bne.s   w1",
        "    bsr.w   rec",
        "    ; 2: only the operation changes, the busy bit is written again",
        "    move.b  #15,$3b(a1)",
        "    move.b  #$80,$3c(a1)",
        "w2:",
        "    btst    #7,$3c(a1)",
        "    bne.s   w2",
        "    bsr.w   rec",
        "    ; 3: the word is set back, a TAS restarts",
        "    move.w  #$1234,$40000",
        "    move.l  #$40000,$32(a1)",
        "    tas     $3c(a1)",
        "w3:",
        "    btst    #7,$3c(a1)",
        "    bne.s   w3",
        "    bsr.w   rec",
        "    ; 4: a Y count of 0 written explicitly",
        "    move.w  #$1234,$40000",
        "    move.l  #$40000,$32(a1)",
        "    move.w  #1,$36(a1)",
        "    move.w  #0,$38(a1)",
        "    move.b  #$80,$3c(a1)",
        "w4:",
        "    btst    #7,$3c(a1)",
        "    bne.s   w4",
        "    bsr.w   rec",
        "    ; 5: an X count of 0 with one line",
        "    move.w  #$1234,$40000",
        "    move.l  #$40000,$32(a1)",
        "    move.w  #0,$36(a1)",
        "    move.w  #1,$38(a1)",
        "    move.b  #$80,$3c(a1)",
        "w5:",
        "    btst    #7,$3c(a1)",
        "    bne.s   w5",
        "    bsr.w   rec",
        "done:",
        "    bra.s   done",
        "",
        "rec:",
        "    move.w  $38(a1),(a2)+",
        "    move.l  $32(a1),(a2)+",
        "    move.b  $3c(a1),(a2)+",
        "    move.b  #0,(a2)+",
        "    move.w  $40000,(a2)+",
        "    rts",
        "",
    ]
    return "\n".join(L)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "p40_blitter_restart.s"), "w", newline="\n") as f:
        f.write(source())
    print("5 experiments")
